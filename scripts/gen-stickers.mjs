// Renders each sticker to a transparent PNG on the backend.
//
// Noto Color Emoji is a BITMAP (CBDT) font, which ImageMagick will not draw - asked
// for a glyph it returns a 1px-wide image and no error. Pillow does, with
// embedded_color=True, so the rendering is handed to a short Python program rather
// than fought with in ImageMagick.
//
// The font has one fixed bitmap size (109pt). Asking for any other size silently
// gives nothing back, so it is always drawn at 109 and scaled afterwards.
//
// Run: node scripts/gen-stickers.mjs [--force]
// Writes backend/public/stickers/<id>.png, served as /stickers/<id>.png.

import { execFile } from 'node:child_process';
import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { promisify } from 'node:util';
import { fileURLToPath } from 'node:url';
import { STICKERS } from '../constants/stickers.js';

const run = promisify(execFile);
const HERE = path.dirname(fileURLToPath(import.meta.url));
const OUT_DIR = path.resolve(HERE, '../../Tonefy-react/backend/public/stickers');
const VERSION_FILE = path.resolve(HERE, '../constants/stickerVersion.js');

// Big enough to sit over 1080p footage without softening. The source bitmap is 136px,
// so this is an upscale - acceptable for a sticker, and the alternative is a font
// that does not exist on this machine.
const SIZE = 320;

const PY = `
import sys, json
from PIL import Image, ImageDraw, ImageFont
font = ImageFont.truetype("/usr/share/fonts/truetype/noto/NotoColorEmoji.ttf", 109)
jobs = json.loads(sys.argv[1])
size = int(sys.argv[2])
done, failed = 0, []
for job in jobs:
    try:
        im = Image.new("RGBA", (160, 160), (0, 0, 0, 0))
        ImageDraw.Draw(im).text((80, 80), job["glyph"], font=font,
                                embedded_color=True, anchor="mm")
        bb = im.getbbox()
        if not bb:
            failed.append(job["id"]); continue
        # Cropped to the ink, then padded square. A sticker placed by its centre must
        # not carry the glyph's own leading around with it, or two stickers dropped on
        # the same spot land in visibly different places.
        im = im.crop(bb)
        side = max(im.size)
        sq = Image.new("RGBA", (side, side), (0, 0, 0, 0))
        sq.paste(im, ((side - im.width) // 2, (side - im.height) // 2))
        sq.resize((size, size), Image.LANCZOS).save(job["out"])
        done += 1
    except Exception as e:
        failed.append(job["id"] + ": " + str(e))
print(json.dumps({"done": done, "failed": failed}))
`;

async function main() {
  await mkdir(OUT_DIR, { recursive: true });
  const jobs = STICKERS.map(s => ({
    id: s.id, glyph: s.glyph, out: path.join(OUT_DIR, `${s.id}.png`),
  }));
  const { stdout } = await run('python3', ['-c', PY, JSON.stringify(jobs), String(SIZE)],
    { timeout: 180000, maxBuffer: 4 * 1024 * 1024 });
  const res = JSON.parse(stdout.trim().split('\n').pop());
  console.log(`rendered ${res.done}, failed ${res.failed.length}`);
  res.failed.forEach(f => console.log('  FAIL', f));

  const stamp = new Date().toISOString().replace(/[-:T]/g, '').slice(0, 12);
  await writeFile(VERSION_FILE,
    '// GENERATED by scripts/gen-stickers.mjs - do not edit.\n'
    + '// Appended to every sticker url, so a re-render reaches phones that cached the\n'
    + '// previous one.\n'
    + `export const STICKER_VERSION = '${stamp}';\n`);
  console.log('sticker version', stamp);
  if (res.failed.length) process.exitCode = 1;
}

main();
