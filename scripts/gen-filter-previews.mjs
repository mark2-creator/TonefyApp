// Renders one preview tile per filter, through the same ffmpeg chain the export runs.
//
// A filter tile has to show the GRADE, which means it has to be a photograph - a
// swatch of colour cannot show what a bleach bypass does to skin, and a grade judged
// against a gradient is a grade judged against nothing. Rendered from the recipe so a
// tile cannot disagree with the result, the same way the transition tiles are.
//
// Run: node scripts/gen-filter-previews.mjs [--only <id>] [--force]
// Writes backend/public/filters/<id>.webp, served as /filters/<id>.webp.

import { execFile } from 'node:child_process';
import { mkdir, access, writeFile, readdir } from 'node:fs/promises';
import { constants } from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { promisify } from 'node:util';
import { fileURLToPath } from 'node:url';
import { FILTERS } from '../constants/filters.js';

const run = promisify(execFile);
const HERE = path.dirname(fileURLToPath(import.meta.url));
const OUT_DIR = path.resolve(HERE, '../../Tonefy-react/backend/public/filters');
// A PORTRAIT, and a specific one, kept apart from the transition photos.
//
// The first version used the transition set's first image, which is a laptop on a
// desk - the worst possible subject for judging a grade. Nearly every filter here is
// built for skin, and a bleach bypass, a portra or a teal-and-orange say nothing at
// all on a keyboard. This frame has a face, hair, white flowers for the highlights
// and sky behind, so a cast shows up in something the eye actually reads.
//
// Refill with scripts/fetch-filter-portrait.sh if the cache is empty.
const SRC_DIR = path.join(os.homedir(), '.cache/tonefy/filter-src');
const VERSION_FILE = path.resolve(HERE, '../constants/filterPreviewVersion.js');

// Portrait, because most of these are graded for skin and that is what the difference
// shows on. Small: 77 of them are on one screen at once.
const W = 150, H = 200;

const args = process.argv.slice(2);
const only = args.includes('--only') ? args[args.indexOf('--only') + 1] : null;
const force = args.includes('--force');

async function exists(p) {
  try { await access(p, constants.F_OK); return true; } catch { return false; }
}

async function main() {
  await mkdir(OUT_DIR, { recursive: true });
  // A POOL of portraits, cycled by catalogue index.
  //
  // One face repeated 150 times reads as a placeholder however good the grades are,
  // which is the whole reason every editor that ships a filter grid uses a different
  // model per tile. Cycling by index rather than at random keeps a tile on the same
  // face between runs, so a regeneration does not reshuffle the whole grid.
  //
  // Works with one file and improves with every file added - drop more portraits into
  // the cache directory and re-run. Adjacent tiles are what matter, so even a handful
  // of faces removes the repetition that a single one cannot.
  const pool = (await readdir(SRC_DIR).catch(() => []))
    .filter(f => /\.(jpe?g|png)$/i.test(f))
    .sort();
  if (!pool.length) {
    console.error(`no portraits in ${SRC_DIR} - run scripts/fetch-filter-portrait.sh`);
    process.exit(1);
  }
  console.log(`${pool.length} portrait(s) in the pool`);

  const list = only ? FILTERS.filter(f => f.id === only) : FILTERS;
  if (!list.length) { console.error('no such filter:', only); process.exit(1); }

  let made = 0, skipped = 0;
  const failed = [];
  for (const f of list) {
    const out = path.join(OUT_DIR, `${encodeURIComponent(f.id)}.webp`);
    if (!force && await exists(out)) { skipped += 1; continue; }
    // Indexed against the FULL catalogue, so --only reproduces the face a full run
    // would have given this tile.
    const src = path.join(SRC_DIR, pool[FILTERS.indexOf(f) % pool.length]);
    const chain = [
      `scale=${W}:${H}:force_original_aspect_ratio=increase`,
      `crop=${W}:${H}`,
      ...(f.chain || []),
    ].join(',');
    try {
      await run('ffmpeg', ['-v', 'error', '-y', '-i', src, '-vf', chain, '-frames:v', '1', out],
        { timeout: 30000 });
      made += 1;
    } catch (err) {
      failed.push({ id: f.id, why: String(err.stderr || err.message).trim().split('\n').pop() });
    }
  }

  console.log(`made ${made}, skipped ${skipped}, failed ${failed.length}`);
  failed.forEach(x => console.log(`  FAIL ${x.id}: ${x.why}`));
  if (failed.length) process.exitCode = 1;

  if (!only) {
    const stamp = new Date().toISOString().replace(/[-:T]/g, '').slice(0, 12);
    await writeFile(VERSION_FILE,
      '// GENERATED by scripts/gen-filter-previews.mjs - do not edit.\n'
      + '// Appended to every filter preview url. Without it a re-render is invisible to\n'
      + '// any phone that cached the previous one, which is a mistake already made once\n'
      + '// with the transition tiles.\n'
      + `export const FILTER_PREVIEW_VERSION = '${stamp}';\n`);
    console.log('preview version', stamp);
  }
}

main();
