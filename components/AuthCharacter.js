/**
 * The figure on the auth screen. She walks in, sets her bag down, the form springs out
 * of it, and she settles into a lean beside it.
 *
 * Art: Humaaans "standing-22" by Pablo Stanley, CC0 - kept in its original colours at
 * the owner's request. It is illustration rather than chrome, which is why it carries
 * no brand green: green is reserved for the control that commits (see tonefy-design),
 * and on this screen that is the sign-in button and nothing else.
 *
 * Drawn as SEPARATE STACKED <Svg> layers sharing one viewBox, rather than one Svg with
 * animated SVG attributes. Rotating a plain View is far more dependable across RN and
 * react-native-svg versions than animating svg's own rotation prop, and a shared
 * viewBox keeps the layers registered for free: a path at (180,115) lands at (180,115)
 * in every layer, whatever size the screen gives them.
 *
 * THE LAYER ORDER IS LOAD-BEARING and getting it wrong is visible. In the source art
 * the far arm paints after the hands but BEFORE the coat front, so it reads as tucked
 * behind her coat; and the head paints before the legs. Both were verified by
 * rebuilding an SVG from this component's own data and pixel-comparing it against the
 * original - a check that also caught a wrapper group carrying translate(34,10) which
 * had been dropped, putting the whole figure 34px right and 10px low while looking
 * perfectly fine side by side.
 *
 *   head
 *   legA, legB      <- rotate in antiphase to walk
 *   near hand
 *   far arm         <- rotates at the shoulder
 *   coat, lapel, buttons
 *
 * The parent owns the choreography. This component knows how to draw her, not when to
 * move.
 */

const VB = '0 0 380 480';

// The source art wraps the whole figure in one more group with this offset. Leaving it
// out shifts her 34px right and 10px down of where she belongs.
